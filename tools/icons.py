PNG_ICONS = ['sparkles', 'house', 'box', 'car', 'timer', 'bell', 'camera', 'note', 'cal', 'check', 'envelope', 'heart', 'intercom', 'cook']


def fetch(kind, name):
    f = SRC / f'{kind}-{name}.svg'
    if not f.exists():
        url = {'f7': F7, 'ph': PH, 'lu': LU}[kind].format(name)
        with urllib.request.urlopen(url, timeout=20) as r:
            body = r.read()
        if b'<svg' not in body[:400]:
            raise SystemExit(f'not an svg: {url}')
        f.write_bytes(body)
    return f.read_text()


def normalize(svg, kind):
    vb = re.search(r'viewBox="([^"]+)"', svg).group(1)
    inner = re.sub(r'^.*?<svg[^>]*>|</svg>\s*$', '', svg.strip(), flags=re.S)
    inner = re.sub(r'<title>.*?</title>|<!--.*?-->', '', inner, flags=re.S)
    if kind == 'lu':      # Lucide is stroked
        return vb, '<g fill="none" stroke="currentColor" stroke-width="2.1" stroke-linecap="round" stroke-linejoin="round">' + inner + '</g>'
    inner = re.sub(r'\sfill="(?!none)[^"]*"', '', inner)
    return vb, '<g fill="currentColor">' + inner + '</g>'


def main():
    SRC.mkdir(parents=True, exist_ok=True); PNG.mkdir(parents=True, exist_ok=True)
    out = {}
    for key, (kind, name) in ICONS.items():
        vb, inner = normalize(fetch(kind, name), kind)
        out[key] = {'vb': vb, 'g': inner}
    (HERE / 'static' / 'icons.js').write_text('/* generated by tools/icons.py from Framework7 Icons (MIT), Phosphor (MIT), Lucide (ISC) */\n'
                                               'var SF = ' + json.dumps(out, separators=(',', ':')) + ';\n'
                                               'function sf(n, cls) { var i = SF[n]; return i ? \'<svg viewBox="\' + i.vb + \'"\' + (cls ? \' class="\' + cls + \'"\' : "") + \'>\' + i.g + "</svg>" : ""; }\n')
    # white PNG glyphs (256 px) for overlays.py, rendered once with headless Chrome
    html = HERE / 'out' / 'icons-sheet.html'
    cells = ''.join(f'<div style="position:absolute;left:{(i % 8) * 256}px;top:{(i // 8) * 256}px;width:256px;height:256px;color:#fff">'
                    f'<svg viewBox="{out[n]["vb"]}" width="256" height="256">{out[n]["g"]}</svg></div>' for i, n in enumerate(PNG_ICONS))
    html.write_text(f'<html><body style="margin:0;background:transparent">{cells}</body></html>')
    rows = (len(PNG_ICONS) + 7) // 8
    sheet = HERE / 'out' / 'icons-sheet.png'
    subprocess.run([CONFIG['chrome_path'], '--headless=new', '--disable-gpu', '--hide-scrollbars',
                    '--default-background-color=00000000', f'--window-size=2048,{rows * 256}', '--screenshot=' + str(sheet),
                    '--user-data-dir=' + str(HERE / 'out' / '.chrome-icons'), html.as_uri()], capture_output=True, timeout=60)
    from PIL import Image
    im = Image.open(sheet).convert('RGBA')
    for i, n in enumerate(PNG_ICONS):
        im.crop(((i % 8) * 256, (i // 8) * 256, (i % 8) * 256 + 256, (i // 8) * 256 + 256)).save(PNG / f'{n}.png')
    print(len(out), 'icons;', len(PNG_ICONS), 'pngs')


if __name__ == '__main__':
    main()
